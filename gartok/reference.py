"""Generate `REFERENCE.md` -- the game's data dictionary for developers, designers and agents -- from the registries.

It is the design-side catalog, spoilers included (creature stats, where a material comes
from). The player's view of the same data is the in-game wiki (`web/wiki_session.py`).

Every catalog in the codebase already carries its own player-facing text: an
`Ability`/`Talent` has a `name` and an `effect`, `data.RACES`/`OCCUPATIONS` are
tables, `world.ARENA_TIERS` are `Bout`s. This walks those and emits one Markdown
reference so nobody hand-maintains a second copy that drifts.

    python -m gartok.reference           # (re)write REFERENCE.md
    python -m gartok.reference --check    # exit 1 if REFERENCE.md is stale

`test_reference.py` runs the `--check` in the suite, so adding an ability or an
item without regenerating fails CI. The prose ruleset (`RULES.md`) is written by
hand and points here for the numbers. A sentence in here is either computed from a
registry or a statement no registry can change; `tests/test_reference.py` pins both.
"""

import sys
from pathlib import Path

from . import (
    abilities,
    archetypes,
    data,
    economy,
    factions,
    hunt,
    items,
    outfit,
    progression,
    sources,
    talents,
    vocations,
    weapon_traits,
)

REFERENCE_PATH = Path(__file__).resolve().parent.parent / "REFERENCE.md"

_BANNER = (
    "<!-- GENERATED by `python -m gartok.reference` from the code registries.\n"
    "     Do not edit by hand: change the table/registry in `gartok/` and "
    "regenerate. -->\n\n"
    "The design catalog, for developers, designers and agents: spoilers included. "
    "Rules prose is `RULES.md`; the player's view of this data is the in-game wiki."
)


def _dice(n, faces):
    return f"{n}d{faces}"


def _table(headers, rows):
    out = ["| " + " | ".join(headers) + " |",
           "|" + "|".join("---" for _ in headers) + "|"]
    for row in rows:
        out.append("| " + " | ".join(str(c) for c in row) + " |")
    return "\n".join(out)


def _ability_ids(race):
    ab = race["ability"]
    return tuple(ab) if isinstance(ab, (tuple, list)) else (ab,) if ab else ()


def _holders():
    """Ability id -> the races and creatures that carry it."""
    held = {}
    for name in data.ALL_RACE_NAMES:
        for aid in _ability_ids(data.race_by_name(name)):
            held.setdefault(aid, []).append(name)
    return held


def _roll_ranges(thresholds):
    prev = 0
    for thr in thresholds:
        yield f"{prev + 1}-{thr}" if thr > prev + 1 else str(thr)
        prev = thr


def _races():
    ranges = _roll_ranges(row[0] for row in data.RACES)
    rows = []
    for rng, r in zip(ranges, (data.race_by_name(n) for n in data.RACE_NAMES)):
        mods = " ".join(f"{v:+d}" for v in r["mods"])
        rows.append((r["name"], rng, mods, f"d{r['hd']}", r["size"], r["language"],
                     f"{r['age_mult']:g}x", abilities.get(r["ability"]).name))
    head = ("Race", "d100", "STR DEX CON INT WIS CHA", "Hit Die", "Size", "Language",
            "Age", "Ability")
    return "## Races\n\nThe playable races. `d100` is the roll that picks one; the modifiers " \
           "are added to the attribute roll.\n\n" + _table(head, rows)


def _drops(race):
    out = []
    if race["drop_item"]:
        out.append(f"{race['drop_item']} ({round(race['drop_chance'] * 100)}%)")
    out += [f"{item} x{qty} ({round(chance * 100)}%)" for item, chance, qty in race["also_drops"]]
    return ", ".join(out) or "--"


def _creatures():
    rows = []
    for name in data.ALL_RACE_NAMES:
        if name in data.RACE_NAMES:
            continue
        r = data.race_by_name(name)
        rows.append((name, r["kind"], " ".join(f"{v:+d}" for v in r["mods"]), f"d{r['hd']}",
                     r["size"], f"{r['speed']:g} m",
                     ", ".join(abilities.get(a).name for a in _ability_ids(r)) or "--", _drops(r)))
    head = ("Creature", "Kind", "STR DEX CON INT WIS CHA", "Hit Die", "Size", "Speed",
            "Abilities", "Drops")
    return ("## Creatures\n\nBodies that are never rolled as a player's race (`data.BEASTS`, "
            "`UNDEAD`, `GIANTS`). A beast has no job: it fights with its own body and drops its "
            "own loot.\n\n" + _table(head, rows))


def _abilities():
    held = _holders()
    rows = [(a.name, ", ".join(held.get(aid, ())) or "--", a.effect)
            for aid, a in abilities.ABILITIES.items()]
    return "## Racial abilities\n\nThe generator kept only the names; every " \
           "effect below was designed for the wargame. Two abilities may share a name " \
           "(Pack Tactics): `Held by` tells them apart.\n\n" \
           + _table(("Ability", "Held by", "Effect"), rows)


def _archetypes():
    rows = []
    for arc in archetypes.ARCHETYPES.values():
        incomp = []
        for a, b in archetypes.INCOMPATIBLE_PAIRS:
            if a == arc.key:
                incomp.append(b)
            elif b == arc.key:
                incomp.append(a)
        rows.append((arc.label, arc.desc, ", ".join(sorted(incomp)) or "--"))
    head = ("Archetype", "Role & Qualification", "Incompatible With")
    if not archetypes.INCOMPATIBLE_PAIRS:
        head, rows = head[:2], [r[:2] for r in rows]
    return "## Squad archetypes\n\nFunctional squad roles for candidate generation " \
           "and commission tokens at the draft.\n\n" + _table(head, rows)


def _vocations():
    rows = [(v.name, ", ".join(v.races), v.perk + ("" if v.active else " (dormant)"))
            for v in vocations.VOCATIONS.values()]
    return ("## Vocations\n\nThe guild's founding trade, picked once at the draft: a set of races "
            "(the draft pool always holds one of each) and one perk for the whole guild.\n\n"
            + _table(("Vocation", "Races", "Perk"), rows))


def _occupations():
    ranges = _roll_ranges(o[0] for o in data.OCCUPATIONS)
    rows = [(o[1], rng, o[2], o[3] or '--') for rng, o in zip(ranges, data.OCCUPATIONS)]
    return "## Occupations\n\nEach occupation grants one starting weapon and one " \
           "starting item. `d100` is the roll that picks it.\n\n" \
           + _table(("Occupation", "d100", "Weapon", "Item"), rows)


def _weapons():
    rows = []
    for name, w in items.weapons().items():
        rng = "melee" if w.range == 0 else f"{w.range} sq"
        thrown = "--" if w.thrown == 0 else f"{w.thrown} sq"
        price = economy._base_price(name) if (name in economy.PRICES or name.startswith(("Large ", "Huge "))) else "--"
        rows.append((name, w.size or "Medium", _dice(*w.damage), rng,
                     "yes" if w.has_trait("finesse") else "--", thrown, w.hands,
                     f"{w.weight:g} kg", price))
    head = ("Weapon", "Size", "Damage", "Range", "Finesse", "Thrown", "Hands", "Weight",
            "Price ($)")
    return "## Weapons\n\n" + _table(head, rows)


def _weapon_traits():
    rows = [(t.name, t.desc) for t in weapon_traits.all_traits()]
    return "## Weapon Traits\n\nProperties and keywords carried by weapons.\n\n" + _table(("Trait", "Description"), rows)


def _armor():
    rows = []
    for name, a in items.armor().items():
        cap = "--" if a.max_dex is None else f"+{a.max_dex}"
        spd = "--" if a.speed_penalty == 0 else f"-{a.speed_penalty} sq"
        guard = f"+{a.guard_bonus}" if a.guard_bonus else "--"
        rows.append((name, f"+{a.ac}", cap, spd, guard, f"{a.weight:g} kg",
                     economy.PRICES.get(name, "--")))
    head = ("Armor", "AC", "Max DEX to AC", "Speed", "Guard test", "Weight", "Price ($)")
    return "## Armor\n\n" + _table(head, rows)


def _shields():
    rows = []
    for name, s in items.shields().items():
        rows.append((name, f"+{s.ac}", f"{s.weight:g} kg",
                     economy.PRICES.get(name, "--")))
    head = ("Shield", "AC", "Weight", "Price ($)")
    return "## Shields\n\n" + _table(head, rows)


def _enemy_kit():
    rows = [(level, cost, f"{cost * outfit.ARMOR_SHARE:.0f}" if level else "--",
             f"{cost * outfit.WEAPON_SHARE:.0f}" if level else "--")
            for level, cost in outfit.KIT_BUDGET.items()]
    head = ("Racial level", "Kit budget ($)", "Armor up to ($)", "Weapon up to ($)")
    return ("## Enemy kit by level\n\nWhat a generated humanoid of each racial level is outfitted "
            f"with (`outfit.py`); the rest of the budget buys up to {outfit.POTION_CAP} "
            f"{outfit.POTION}s. Level 0 keeps the occupation's kit; beasts carry none.\n\n"
            + _table(head, rows))


GROUP_MIN = 3


def _items():
    """Everything that is not a weapon, armor or shield (those have their own tables); items that
    differ only after an " of " (the dictionaries, the scrolls) share one row."""
    own = set(items.weapons()) | set(items.armor()) | set(items.shields())
    groups = {}
    for name, item in sorted(items.all_items().items()):
        if name in own:
            continue
        tags = []
        if item.food:
            tags.append("food")
        if items.is_consumable(item):
            tags.append("consumable")
        if items.is_material(item):
            tags.append("material")
        if name in data.LIGHT_SOURCES:
            tags.append(f"light {data.LIGHT_SOURCES[name]} sq")
        prefix, sep, tail = name.partition(" of ")
        key = (prefix if sep else name, f"{item.weight:g} kg", ", ".join(tags) or "--",
               economy.PRICES.get(name) or "--")
        groups.setdefault(key, []).append((name, tail))
    rows = []
    for (prefix, weight, notes, price), members in groups.items():
        if len(members) >= GROUP_MIN:
            rows.append((f"{prefix} of ({', '.join(t for _, t in members)})", weight, notes, price))
        else:
            rows += [(n, weight, notes, price) for n, _ in members]
    return "## Items\n\nEverything that is not a weapon, armor or shield (see their tables). " \
           "A row with a bracket stands for one item per name inside it.\n\n" \
           + _table(("Item", "Weight", "Notes", "Price ($)"), rows)


def _base_materials():
    rows = [(n, ", ".join(f"{s.kind}: {s.where}" for s in sources.sources_of(n)))
            for n in sources.base_materials()]
    return "## Base materials\n\nRaw goods no recipe makes, and where each comes from " \
           "(`gartok/sources.py`).\n\n" + _table(("Item", "Source"), rows)


def _sizes():
    rows = [(name, f"{s['speed']:g} m ({data.squares(s['speed'])} sq)",
             f"x{s['carry']:g}", f"{s['footprint']}x{s['footprint']}",
             _dice(*data.UNARMED_ATTACK[name]))
            for name, s in data.SIZES.items()]
    head = ("Size", "Speed", "Carry mult.", "Footprint", "Unarmed")
    return "## Sizes\n\n" + _table(head, rows)


def _alignments():
    orders, morals = [], []
    for _, name in data.ALIGNMENTS:
        order, moral = name.split(" and ")
        orders += [order] * (order not in orders)
        morals += [moral] * (moral not in morals)
    return (f"## Alignments\n\nTwo axes -- order ({'/'.join(orders)}) and morality "
            f"({'/'.join(morals)}) -- {len(data.ALIGNMENTS)} combinations in `data.ALIGNMENTS`, "
            "each with a d100 band.")


def _curve(curve, shown=20):
    return f"`{curve.text}` for level n, no top: " + ", ".join(map(str, curve.first(shown))) + ", ..."


def _talent_trees():
    out = ["## Talent trees\n\nOne tree per track. A new level in a track grants "
           "one pick in its tree; `Requires` gates the deeper nodes. The racial "
           "track's level is `combat + work + magic` on a scale "
           f"(`progression.RACIAL_XP_THRESHOLDS`) and grants a pick every {progression.RACIAL_PICK_EVERY} "
           "racial levels; its nodes are race-gated, grouped by race below. The magic track is "
           "school-agnostic."]
    for track in talents.TRACKS:
        racial = track == "racial"
        nodes = talents.TREE[track]
        if racial:
            nodes = sorted(nodes, key=lambda t: (t.races[0] if t.races else "", t.tier, t.name))
        head = (("Race",) if racial else ()) + ("Tier", "Talent", "Effect", "Requires")
        rows = [((", ".join(t.races) or "any",) if racial else ())
                + (t.tier, t.name, t.effect,
                   "granted" if t.granted else talents.get(t.requires).name if t.requires else "--")
                for t in nodes]
        out.append(f"### {track.capitalize()} track\n\n" + _table(head, rows))
    return "\n\n".join(out)


def _factions():
    out = ["## Factions and deeds\n\nReputation moves only by completing deeds "
           "(one-shot achievements) -- there is no per-win grind."]
    for fid, fac in factions.FACTIONS.items():
        rows = [(d.name, d.blurb, f"+{d.rep}",
                 factions.DEEDS[d.requires].name if d.requires else "--")
                for d in factions.DEEDS_BY_FACTION[fid]]
        body = (_table(("Deed", "Condition", "Rep", "Requires"), rows) if rows
                else "_No deeds yet -- standing with this faction does not move._")
        out.append(f"### {fac.name}\n\n{fac.blurb}\n\n" + body)
    return "\n\n".join(out)





